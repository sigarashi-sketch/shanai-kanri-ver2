// ヘッダー／フッターの文字から、左（L）・中央（C）・右（R）の1か所ぶんを取り出す。書式の記号は捨てる。&P（ページ番号）&D（日付）&A（シート名）などは残す
const hf = (s: string, sec: 'L' | 'C' | 'R') => {
  let cur = 'C', out = '';
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c !== '&') { if (cur === sec) out += c; continue; }
    const n = s[i + 1] || '', N = n.toUpperCase();
    if (N === 'L' || N === 'C' || N === 'R') { cur = N; i++; }
    else if (n === '"') { const j = s.indexOf('"', i + 2); i = j < 0 ? s.length : j; }
    else if (/\d/.test(n)) { while (/\d/.test(s[i + 1] || '')) i++; }
    else if (N === 'K') i += 7;
    else if (n === '&') { if (cur === sec) out += '&'; i++; }
    else { if (cur === sec) out += '&' + N; i++; }
  }
  return norm(out);
};
