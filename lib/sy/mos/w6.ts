//   ・「作成する」の判定は ブック全体のグラフから探す（作ったあとで グラフ シートへ動かしても 落ちないように）
//   ・グラフ スタイルと 色の変更は 保存ファイルから読めない（Excel はどのグラフにも c:style=2 を書く。2013 以降のスタイルは別の部品に入る）ので 選ぶ問題にしてある

// ── 手順の書き分け（グラフのタブは 版で名前が違う） ──
const gd = (rest: string): HowLine => ({ win: `[グラフのデザイン] タブ → ${rest}`, mac: `[グラフのデザイン] タブ → ${rest}`, v: { '2016': `[グラフ ツール] の [デザイン] タブ → ${rest}`, '2019': `[グラフ ツール] の [デザイン] タブ → ${rest}` } });
const add = (path: string): HowLine => gd(`[グラフのレイアウト] グループ → [グラフ要素を追加] → ${path}`);
const PICK = 'グラフの白い所（グラフ エリア）をクリックして、グラフを選びます。選ぶと グラフ用のタブが出ます';
const PLUS = { win: 'グラフの右上に出る ＋ のボタン（[グラフ要素]）からでも 同じことができます', mac: 'Mac には ＋ のボタンがありません。[グラフ要素を追加] から行います' };
const ins = (btn: string, kind: string, macBtn: string): HowLine => ({ win: `[挿入] タブ → [グラフ] グループ → [${btn}] → ${kind}`, mac: `[挿入] タブ → ${macBtn}のアイコン（[${btn}]）→ ${kind}` });

// ── 判定の道具 ──
const sers = (c: RChart | null) => (c ? c.series.filter((s) => !!s.val) : []);
const onSheet = (ref: string, sheet: string) => norm(refKey(ref).split('!')[0]) === norm(sheet);
// sheet のデータで作ったグラフか（系列が1つ以上あって、ぜんぶ そのシートを見ている）
const from = (c: RChart, sheet: string) => sers(c).length > 0 && sers(c).every((s) => onSheet(s.val, sheet));
// 系列の値が data（数字の入っている範囲）と ぴったり同じか。行／列 どちら向きの系列でも よい
const fits = (c: RChart, data: string) => sers(c).every((s) => covers(data, s.val)) && covers(sers(c).map((s) => refOnly(s.val)).join(','), data);
const made = (b: Bk, sheet: string, type: 'col' | 'bar' | 'line' | 'pie') => b.charts.filter((c) => G.is(c, type) && from(c, sheet));
const rowWise = (ref: string) => { const [s, e] = refOnly(ref).split(':'); const p = a1(s), q = a1(e || s); return !!p && !!q && p.r === q.r && p.c !== q.c; };
const same = (x: unknown, y: string) => norm(x) === norm(y);
const valAxes = (c: RChart | null) => (c ? c.axes.filter((x) => x.kind === 'val') : []);

