// タイピングの点（100点）= 速さ 70点（TYPING_FULL_KPM 打/分で満点）＋ 正確さ 30点（TYPING_MIN_ACC で 0点、100% で満点）
//   ★数字は Claude の仮置き（240打/分 = タイピング検定の2級と同じ線）
export const TYPING_FULL_KPM = 240;
export const TYPING_MIN_ACC = 0.8;
export function typingScore(kpm: number, accuracy: number): number {
  const speed = Math.min(1, Math.max(0, kpm / TYPING_FULL_KPM)) * 70;
  const acc = Math.min(1, Math.max(0, (accuracy - TYPING_MIN_ACC) / (1 - TYPING_MIN_ACC))) * 30;
  return Math.round(speed + acc);
}

