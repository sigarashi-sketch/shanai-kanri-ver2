// 近い値どうしを1つの組にする（行・列を見つける）
function cluster(els: NEl[], key: 'x' | 'y', tol = 30): NEl[][] {
  const out: NEl[][] = [];
  for (const e of [...els].sort((a, b) => a[key] - b[key])) { const g = out.find((x) => Math.abs(x[0][key] - e[key]) <= tol); if (g) g.push(e); else out.push([e]); }
  return out;
}
