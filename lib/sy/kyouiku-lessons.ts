// 経験値とレベル（画面だけの計算。DBには持たない＝進み具合から毎回出す・2026-10-02 shoya「敵を倒したら経験値獲得画面」）
//   敵を倒す（クエストをクリアする）と、ステップ数×10（ボスは +30）の経験値。次のレベルまでは 30 → 40 → 50…と 10 ずつ増える
export const questExp = (q: Quest, steps = q.steps.length) => steps * 10 + (q.enemy.boss ? 30 : 0);
export const expOf = (quests: QuestProgress[]) => quests.reduce((s, p, k) => s + (p.cleared && QUESTS[k] ? questExp(QUESTS[k], p.total) : 0), 0);
export function levelOf(exp: number): { lv: number; into: number; need: number } {
  let lv = 1, need = 30, into = Math.max(0, Math.floor(exp));
  while (into >= need) { into -= need; lv++; need += 10; }
  return { lv, into, need };
}

// A1 形式 ⇔ 行列
export function a1(addr: string): { r: number; c: number } | null {
  const m = /^([A-Z]+)(\d+)$/.exec(String(addr || '').toUpperCase());
  if (!m) return null;
  let c = 0; for (const ch of m[1]) c = c * 26 + (ch.charCodeAt(0) - 64);
  return { r: Number(m[2]) - 1, c: c - 1 };
}
export function inRange(addr: string, range: string): boolean {
  const [s, e] = String(range || '').split(':'); const p = a1(addr), a = a1(s), b = a1(e || s);
  if (!p || !a || !b) return false;
  return p.r >= a.r && p.r <= b.r && p.c >= a.c && p.c <= b.c;
}
