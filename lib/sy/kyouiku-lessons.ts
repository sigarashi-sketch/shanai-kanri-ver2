//   2026-10-02 shoya「実践型の教育コンテンツ。動画で説明→スプシで1つずつ入力→答え合わせ。ゲーム感覚（クエスト型）」
//   ・ワールド0（キーボードとセルの基本）→ ワールド1（スプシの基本＝入門＋クエスト3つ）→ ワールド2（実践）→ ワールド3（現場編＝経理事務）。各4クエスト（マップが4マスのため）
//     クエストを足すときは gid（練習用スプシのタブの番号）を必ず新しい数字にする。既に配ったスプシのタブとつながっているので、あとから変えない
//   ・動画は音声なし・字幕だけ。台本（slides）から画面の中で再生する（動画ファイルは作らない）
//   ・練習用スプシは1人1冊（タブ＝クエスト）。サーバが作って本人に共有する（lib/kyouiku-sheet.ts。最初の表は下の grid）

export type Cell = string | number;
export interface Slide {
  cap: string;                     // 字幕（1〜2行）
  cell?: string;                   // 枠で囲むセル（例 'D2'）
  range?: string;                  // 色を塗る範囲（例 'B2:B7'）
  typed?: string;                  // 数式バーに打ち込む文字（1文字ずつ出る）
  show?: Record<string, Cell>;     // このコマで表に出す値（入力後の結果など。'' で消えた様子）
  keys?: string[];                 // このコマで押すキー（例 ['Ctrl', 'C']）。字幕の上にキーの絵で出す
}
export interface Step { title: string; body: string; cells: string[] }   // cells = 答え合わせで見るセル（場所だけ）
// 敵（クエストごとのモンスター。オリジナルの「セルのおばけ」）。HP＝ステップ数、1ステップ正解で1ダメージ
export interface Enemy { name: string; body: string; boss?: boolean }
export interface Quest {
  id: string; gid: number; no: string; title: string; goal: string; tab: string; place: string; enemy: Enemy;   // gid = 練習用スプシのタブの番号（固定）
  grid: Cell[][];                  // 練習用シートの最初の状態（A1 から）。動画の表もこれを使う
  vgrid?: Cell[][];                // 動画の表だけ 別の中身にしたい時（長い URL を縮める等・応用編）。無ければ grid
  frozen?: number;                 // 練習用シートで固定しておく行数（無ければ 1。実務編の「見出しを固定」は 0 から始める）
  slides: Slide[];
  steps: Step[];
}

